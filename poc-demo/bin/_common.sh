#!/usr/bin/env bash
# Shared helpers for the BNaaS demo stack scripts. Sourced, not executed.
#
# Reads PORT_OFFSET from the environment or demo/.env, derives every
# published port from it, rewrites the derived block of demo/.env so a bare
# `docker compose` picks the same values up, and exports them.

set -euo pipefail

# bash only: this file uses indirect expansion and array key expansion, so
# sourcing it from zsh fails on `bad substitution`. Every script in bin/ has
# a bash shebang, so run those rather than sourcing this by hand from an
# interactive zsh. `bash -c '. bin/_common.sh; load_env; ...'` also works.
if [ -z "${BASH_VERSION:-}" ]; then
    printf '!!  bin/_common.sh needs bash. Run the bin/ scripts, or wrap it: bash -c ". bin/_common.sh; load_env; ..."\n' >&2
    return 1 2>/dev/null || exit 1
fi

DEMO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$DEMO_DIR/.env"
COMPOSE_FILE="$DEMO_DIR/docker-compose.yaml"
DERIVED_MARKER='# ---- derived (regenerated by bin/_common.sh, do not edit) ----'

# base ports, i.e. what PORT_OFFSET=0 gives. Order is the order written.
PORT_NAMES=(ZK_PORT KAFKA_PORT REDIS_PORT MONGO_PORT PROMETHEUS_PORT \
            GRAFANA_PORT KAFKA_UI_PORT KAFKA_EXPORTER_PORT ZOONAV_PORT \
            CLOUDSERVER_PORT KRB_KDC_PORT KRB_BROKER_PORT KRB_VERIFY_PORT)
# CLOUDSERVER_PORT's base is 8010, not 8000: an unrelated local process holds
# 8000 on this machine, and 8010 is the port the process scripts already use.
PORT_BASES=(2181 9092 6379 27117 9090 3000 8085 9308 9000 8010 1088 19095 19096)

say()  { printf '==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf '!!  %s\n' "$*" >&2; }
die()  { printf '!!  %s\n' "$*" >&2; exit 1; }

# read one key from .env, ignoring the derived block
env_knob() {
    local key="$1"
    sed -n "s/^${key}=//p" "$ENV_FILE" | tail -1
}

# rewrite the derived block from PORT_OFFSET, then export everything
load_env() {
    [ -f "$ENV_FILE" ] || die "missing $ENV_FILE"

    local offset="${PORT_OFFSET:-}"
    if [ -z "$offset" ]; then
        offset="$(env_knob PORT_OFFSET)"
    fi
    [ -n "$offset" ] || die "PORT_OFFSET is not set in $ENV_FILE"
    case "$offset" in (*[!0-9]*) die "PORT_OFFSET must be a number, got '$offset'";; esac

    local tmp i name port derived_kv
    grep -qF -- "$DERIVED_MARKER" "$ENV_FILE" || die "no derived marker in $ENV_FILE"

    # build KEY=VALUE pairs for the derived ports
    derived_kv=""
    for i in "${!PORT_NAMES[@]}"; do
        name="${PORT_NAMES[$i]}"
        port=$(( PORT_BASES[i] + offset ))
        derived_kv="${derived_kv}${name}=${port}"$'\n'
    done
    derived_kv="${derived_kv}KAFKA_INTERNAL_PORT=29092"$'\n'

    # Update those keys in place and append the ones that are missing just
    # after the marker. Other agents write process scripts that read this
    # same file, so nothing outside the keys above is touched.
    tmp="$(mktemp)"
    printf '%s' "$derived_kv" | awk -v marker="$DERIVED_MARKER" '
        NR == FNR { split($0, kv, "="); want[kv[1]] = $0; order[++n] = kv[1]; next }
        {
            split($0, kv, "=")
            if (kv[1] in want) { print want[kv[1]]; seen[kv[1]] = 1; next }
            print
            if (index($0, marker) == 1) { at_marker = NR - FNR }
        }
        END {
            for (i = 1; i <= n; i++)
                if (!(order[i] in seen)) print want[order[i]]
        }
    ' - "$ENV_FILE" > "$tmp"

    if cmp -s "$tmp" "$ENV_FILE"; then
        rm -f "$tmp"
    else
        mv "$tmp" "$ENV_FILE"
        say "derived ports in .env rewritten from PORT_OFFSET=$offset"
    fi

    # Export every knob and derived value, for docker compose and for us,
    # but let a value already in the environment win, which is how docker
    # compose itself treats .env. That is what makes a one-off override
    # work without editing the shared file:
    #   CLOUDSERVER_PORT=9011 bin/stack-up.sh
    local k kv saved=()
    while IFS='=' read -r k _; do
        # an `if` and not a && list, so a false test never trips set -e
        if [ -n "${!k+x}" ]; then
            saved+=("$k=${!k}")
        fi
    done < <(grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$ENV_FILE" | tr -d '=')
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    set +a
    for kv in "${saved[@]}"; do
        export "${kv?}"
    done
    PORT_OFFSET="$offset"
    export PORT_OFFSET
    PROJECT="${COMPOSE_PROJECT_NAME:-bnaasdemo}"
    export PROJECT
}

dc() {
    docker compose --project-name "$PROJECT" --file "$COMPOSE_FILE" "$@"
}

# docker compose with the krb profile added
dck() {
    docker compose --project-name "$PROJECT" --file "$COMPOSE_FILE" --profile krb "$@"
}

kafka_ctr() { printf '%s-kafka-1' "$PROJECT"; }
mongo_ctr() { printf '%s-mongo-1' "$PROJECT"; }
zk_ctr()    { printf '%s-zookeeper-1' "$PROJECT"; }
cs_ctr()    { printf '%s-cloudserver-1' "$PROJECT"; }

# zkCli inside the zookeeper container. Prints the raw zkCli output, which
# wraps the answer in log lines; callers filter.
zk_cli() {
    docker exec -i "$(zk_ctr)" zkCli.sh -server "localhost:2181" "$@" 2>/dev/null
}

# kafka CLI inside the broker container, over the host-facing listener,
# which inside the container is 0.0.0.0:${KAFKA_PORT}
kafka_cli() {
    local tool="$1"; shift
    docker exec -i "$(kafka_ctr)" "/opt/kafka/bin/${tool}" \
        --bootstrap-server "localhost:${KAFKA_PORT}" "$@"
}

port_busy() { nc -z 127.0.0.1 "$1" >/dev/null 2>&1; }

# Which container, if any, publishes a host port. Asks docker with a filter
# rather than parsing the Ports column: a published range prints as
# "20095-20096->20095-20096/tcp", which no substring match on a single port
# will ever find, and the whole preflight then calls our own container a
# foreign owner.
port_owner() {
    docker ps --filter "publish=$1" --format '{{.Names}}' | head -1
}

wait_for() {
    local what="$1" timeout="$2"; shift 2
    local deadline=$(( $(date +%s) + timeout ))
    until "$@" >/dev/null 2>&1; do
        if [ "$(date +%s)" -ge "$deadline" ]; then
            warn "timed out after ${timeout}s waiting for $what"
            return 1
        fi
        sleep 2
    done
    info "$what ready"
}

