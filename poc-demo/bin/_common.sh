    printf '                 workgroups doc %s   populator offsets %s\n' "$ZK_WORKGROUPS_PATH" "$ZK_POPULATOR_PATH"
    printf '    exporter     http://localhost:%s/metrics\n' "$KAFKA_EXPORTER_PORT"
    printf '    s3 endpoint  http://localhost:%s   (accessKey1 / verySecretKey1)\n' "$CLOUDSERVER_PORT"
    printf '    kafka        localhost:%s   (host processes)   kafka:%s (containers)\n' "$KAFKA_PORT" "$KAFKA_INTERNAL_PORT"
    printf '    zookeeper    localhost:%s\n' "$ZK_PORT"
    printf '    redis        localhost:%s\n' "$REDIS_PORT"
    printf '    mongo        mongodb://localhost:%s/?replicaSet=rs0\n' "$MONGO_PORT"
}
